import { test, expect, type Page } from "@playwright/test";
import { Pool } from "pg";
import { randomBytes, createHash } from "node:crypto";

let pool: Pool;
const createdEmails: string[] = [];
const password = randomBytes(20).toString("base64url");
test.beforeAll(async () => {
  const url = new URL(process.env.DATABASE_URL || "");
  if (url.pathname !== "/wax_development" || url.username !== "wax_development")
    throw new Error(
      "Browser fixtures require the isolated wax_development database.",
    );
  pool = new Pool({ connectionString: url.href, max: 2 });
});
test.afterAll(async () => {
  if (!pool) return;
  // Remove only accounts generated by this worker; never truncate application tables.
  for (const email of createdEmails) {
    await pool.query("DELETE FROM wax.invitations WHERE email=$1", [email]);
    await pool.query("DELETE FROM wax.users WHERE email=$1", [email]);
  }
  await pool.end();
});
async function join(page: Page) {
  // Simulate independent clients; Vercel supplies this header in deployment.
  await page.context().setExtraHTTPHeaders({
    "x-real-ip": `192.0.2.${1 + (randomBytes(1)[0] % 253)}`,
  });
  const email = `wax-e2e-${randomBytes(8).toString("hex")}@example.com`;
  const token = randomBytes(32).toString("base64url");
  createdEmails.push(email);
  await pool.query(
    "INSERT INTO wax.invitations(email,token_hash,kind,expires_at) VALUES($1,$2,'collector',now()+interval '1 hour')",
    [email, createHash("sha256").update(token).digest("hex")],
  );
  await page.goto("/join#token=" + token);
  await page.getByLabel("Full name").fill("WAX browser test");
  await page.getByLabel("Password", { exact: false }).fill(password);
  await page.getByRole("button", { name: "Open my collection" }).click();
  // Join may sign in automatically or ask for a separate sign-in.
  await expect(page).toHaveURL(/\/(collection|sign-in)/);
  if (page.url().includes("/sign-in")) {
    await page.getByLabel("Email address").fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
  }
  await expect(page).toHaveURL(/\/collection/);
  await expect(
    page.getByRole("heading", { name: "The collection" }),
  ).toBeVisible();
  return email;
}

test("invited collector adds a copy, reloads Neon data, and stays private", async ({
  page,
  browser,
}) => {
  await join(page);
  await expect(
    page.getByText("AN EMPTY CRATE. ENDLESS POSSIBILITIES."),
  ).toBeVisible();
  await page.screenshot({
    path: `test-results/empty-${test.info().project.name}.png`,
    fullPage: true,
  });
  await page.goto("/add?mode=manual");
  await page.getByRole("button", { name: "Enter the details" }).click();
  await page.getByLabel("Artist", { exact: true }).fill("Curtis Mayfield");
  await page.getByLabel("Record title").fill("Super Fly");
  await page.getByLabel("Album release year", { exact: false }).fill("1972");
  await page.getByLabel("Your liner notes").fill("Private QA note");
  await page.getByLabel("Purchase price").fill("18.50");
  await page.getByRole("button", { name: "Add to my collection" }).click();
  await expect(page).toHaveURL(/\/records\/[a-f0-9-]+/);
  const recordUrl = page.url();
  await page.reload();
  await expect(
    page.getByRole("heading", { name: "Super Fly", exact: true }),
  ).toBeVisible();
  const own = await page.request.get("/api/library");
  expect(own.ok()).toBeTruthy();
  const library = await own.json();
  expect(library.records).toHaveLength(1);
  expect(library.records[0]).toMatchObject({
    artist: "Curtis Mayfield",
    title: "Super Fly",
    originalYear: 1972,
    year: null,
    notes: "Private QA note",
    purchasePrice: "18.50",
  });
  await page.getByRole("button", { name: "Log a spin", exact: true }).click();
  await page.getByLabel("Listening notes").fill("A proper first spin.");
  await page.getByRole("button", { name: "Log this spin" }).click();
  await expect(
    page.getByText("Another good spin, on the record."),
  ).toBeVisible();
  await page.getByRole("button", { name: "QR label" }).click();
  await expect(
    page.getByRole("img", { name: "QR code for your private record page" }),
  ).toBeVisible();
  await page.getByRole("button", { name: "Close dialog" }).click();
  const outsider = await browser.newContext();
  const unauthorized = await outsider.request.get(
    recordUrl.replace("/records/", "/api/records/"),
  );
  expect(unauthorized.status()).toBe(401);
  await outsider.close();
  await page.goto("/collection");
  await page.getByRole("button", { name: "Table view" }).click();
  await expect(page.getByRole("table")).toContainText("Super Fly");
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= window.innerWidth + 1,
    ),
  ).toBeTruthy();
  await page.screenshot({
    path: `test-results/collection-${test.info().project.name}.png`,
    fullPage: true,
  });
});

test("camera denial and upload or AI failures preserve a recoverable photo draft", async ({
  page,
}) => {
  await page.addInitScript(() => {
    if (!navigator.mediaDevices) {
      Object.defineProperty(navigator, "mediaDevices", { value: {} });
    }
    Object.defineProperty(navigator.mediaDevices, "getUserMedia", {
      value: () =>
        Promise.reject(new DOMException("Test denial", "NotAllowedError")),
    });
  });
  await join(page);
  await page.goto("/add?mode=scan");
  await page.getByRole("button", { name: "Open camera", exact: true }).click();
  await expect(
    page.getByText("Camera access was denied.", { exact: false }),
  ).toBeVisible();
  await page.getByLabel("Or type the barcode").fill("886976805715");
  await expect(page.getByLabel("Or type the barcode")).toHaveValue(
    "886976805715",
  );
  await page.goto("/add?mode=photo");
  let uploads = 0;
  let identifications = 0;
  await page.route("**/api/photos", (route) => {
    uploads++;
    return route.fulfill({
      status: uploads === 1 ? 503 : 200,
      contentType: "application/json",
      body: JSON.stringify(
        uploads === 1
          ? { error: "Photo upload unavailable. Please retry." }
          : {
              id: "00000000-0000-4000-8000-000000000001",
              url: "/api/photos/00000000-0000-4000-8000-000000000001",
            },
      ),
    });
  });
  await page.route("**/api/identify", (route) => {
    identifications++;
    return route.fulfill({
      status: identifications === 1 ? 503 : 200,
      contentType: "application/json",
      body: JSON.stringify(
        identifications === 1
          ? { error: "Recognition unavailable. Your photo is saved; retry." }
          : {
              photoId: "00000000-0000-4000-8000-000000000001",
              clues: {
                artist: "Curtis Mayfield",
                title: "Super Fly",
                label: null,
                barcode: null,
                catalogNumber: null,
                uncertainty: "Test photograph; compare the pressing.",
              },
              candidates: [],
            },
      ),
    });
  });
  await page.locator('input[type="file"]').setInputFiles({
    name: "fixture.png",
    mimeType: "image/png",
    buffer: await page.screenshot({ type: "png" }),
  });
  await page.getByRole("button", { name: "Identify this record" }).click();
  await expect(
    page.getByText("Photo upload unavailable. Please retry."),
  ).toBeVisible();
  await expect(page.getByAltText("Your selected record photo")).toBeVisible();
  await page.getByRole("button", { name: "Identify this record" }).click();
  await expect(
    page.getByText("Recognition unavailable. Your photo is saved; retry."),
  ).toBeVisible();
  await page.getByRole("button", { name: "Identify this record" }).click();
  await expect(page.getByLabel("Artist", { exact: true })).toHaveValue(
    "Curtis Mayfield",
  );
  expect(uploads).toBe(2);
  expect(identifications).toBe(2);
});

test("catalog and barcode candidates retain a manual path when throttled", async ({
  page,
}) => {
  await join(page);
  await page.goto("/add");
  await page
    .getByLabel("Search the record catalog")
    .fill("Curtis Mayfield Super Fly");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(
    page.getByRole("button", { name: "Review this pressing" }).first(),
  ).toBeVisible();
  await page
    .getByRole("button", { name: "Review this pressing" })
    .first()
    .click();
  await expect(page.getByLabel("Artist", { exact: true })).not.toBeEmpty();
  await expect(
    page.getByRole("checkbox", { name: /I’ve checked this pressing/ }),
  ).not.toBeChecked();
  // Test provider failure at the HTTP boundary, preserving all client state.
  await page.goto("/add?mode=scan");
  await page.getByLabel("Or type the barcode").fill("886976805715");
  await page.getByRole("button", { name: "Find matches" }).click();
  await expect(
    page.getByRole("button", { name: "Review this pressing" }).first(),
  ).toBeVisible();
  await page.route("**/api/catalog?**", (route) =>
    route.fulfill({
      status: 429,
      contentType: "application/json",
      body: JSON.stringify({
        error: "Catalog is busy. Please try again shortly.",
      }),
    }),
  );
  await page.getByRole("button", { name: "Find matches" }).click();
  await expect(
    page.getByRole("alert").filter({ hasText: "Catalog is busy" }),
  ).toBeVisible();
  await expect(page.getByLabel("Or type the barcode")).toHaveValue(
    "886976805715",
  );
  await page
    .getByRole("button", { name: "Add by hand", exact: true })
    .first()
    .click();
  await page.getByRole("button", { name: "Enter the details" }).click();
  await expect(page.getByLabel("Record title")).toBeVisible();
});
